    def _wait_for_task_current(
        self,
        project_id: str,
        *,
        expected_status: str | None = None,
        expected_phase: str | None = None,
        expected_confirmation_kind: str | None = None,
        timeout_seconds: float = 5.0,
    ) -> dict:
        """
        接口注释：
        轮询当前任务接口，直到任务进入指定状态。

        设计注释：
        生成、确认后的继续处理现在走应用级后台任务。
        合同测试不能再假设“接口一返回，后台阶段就已经同步跑完”，
        所以这里统一等到下一阶段真的落库后再断言。
        """

        deadline = time.monotonic() + timeout_seconds
        last_payload: dict | None = None
        while time.monotonic() < deadline:
            response = self.client.get(f"/api/projects/{project_id}/task/current")
            self.assertEqual(response.status_code, 200)
            payload = response.json()
            last_payload = payload
            confirmation_data = payload.get("confirmationData")
            confirmation_kind = (
                confirmation_data.get("confirmationKind")
                if isinstance(confirmation_data, dict)
                else None
            )
            if expected_status is not None and payload.get("status") != expected_status:
                time.sleep(0.05)
                continue
            if expected_phase is not None and payload.get("activePhase") != expected_phase:
                time.sleep(0.05)
                continue
            if expected_confirmation_kind is not None and confirmation_kind != expected_confirmation_kind:
                time.sleep(0.05)
                continue
            return payload
        raise AssertionError(f"Task current payload did not reach expected state: {last_payload}")

