    def test_spawn_scheduled_app_task_tracks_and_removes_completed_task(self) -> None:
        async def scenario() -> None:
            marker: list[str] = []

            async def worker() -> None:
                marker.append("ran")

            task = _spawn_scheduled_app_task(worker(), task_label="unit-test-worker")
            self.assertIn(task, app.state.scheduled_background_tasks)
            await task
            await asyncio.sleep(0)
            self.assertEqual(marker, ["ran"])
            self.assertNotIn(task, app.state.scheduled_background_tasks)

        asyncio.run(scenario())

    def test_await_scheduled_app_tasks_shutdown_cancels_running_tasks(self) -> None:
        async def scenario() -> None:
            cancelled = asyncio.Event()

            async def worker() -> None:
                try:
                    await asyncio.Event().wait()
                except asyncio.CancelledError:
                    cancelled.set()
                    raise

            task = _spawn_scheduled_app_task(worker(), task_label="shutdown-worker")
            await asyncio.sleep(0)
            await _await_scheduled_app_tasks_shutdown(timeout_seconds=0.1)
            self.assertTrue(cancelled.is_set())
            self.assertTrue(task.cancelled())

        asyncio.run(scenario())

